package vm

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/kernel-guard/bpfcompat/internal/matrix"
)

// generatedSweepHeader marks matrices written by `bpfcompat kernel-sweep`.
// They mark every exact-release target required and are regenerated, not
// edited, so they are a per-release freshness lane rather than a
// hand-maintained support claim.
const generatedSweepHeader = "# Generated by `bpfcompat kernel-sweep"

// handMaintainedMatrix is one committed matrix that is not a generated
// kernel-sweep matrix, loaded with the runner's own matrix semantics.
type handMaintainedMatrix struct {
	file string
	m    matrix.Matrix
}

func loadHandMaintainedMatrices(t *testing.T, root string) []handMaintainedMatrix {
	t.Helper()
	paths, err := filepath.Glob(filepath.Join(root, "matrices", "*.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var out []handMaintainedMatrix
	for _, path := range paths {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if bytes.Contains(raw, []byte(generatedSweepHeader)) {
			continue
		}
		m, err := matrix.LoadBytes(raw)
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		out = append(out, handMaintainedMatrix{file: filepath.Base(path), m: m})
	}
	if len(out) == 0 {
		t.Fatal("no hand-maintained matrices found")
	}
	return out
}

// requiredLockdownEntries returns the ids of lockdown-named profiles that m
// gates on. It uses RequiredBool, the runner's semantics, so an entry that
// omits `required` counts as required.
func requiredLockdownEntries(m matrix.Matrix, lockdownNamed map[string]bool) []string {
	var out []string
	for _, entry := range m.Profiles {
		if lockdownNamed[entry.ID] && entry.RequiredBool() {
			out = append(out, entry.ID)
		}
	}
	return out
}

// requiredCount counts the targets RunVerdict will gate on.
func requiredCount(m matrix.Matrix) int {
	n := 0
	for _, entry := range m.Profiles {
		if entry.RequiredBool() {
			n++
		}
	}
	return n
}

// Kernel lockdown is a claim about the guest's security posture, and nothing
// in the executor establishes it: x86_64 guests boot with legacy BIOS (no
// Secure Boot), no profile can add lockdown= to the kernel command line, and
// reports do not record /sys/kernel/security/lockdown. The
// ubuntu-22.04-5.15-lockdown lineage advertised lockdown in its version
// ("22.04-lockdown") and was required in two matrices, while its guest reports
// "[none]" (docs/profile-claims.md). Until a profile can establish lockdown
// and a report can show it, a lockdown-named profile must not advertise the
// posture in its version and must not gate a hand-maintained matrix.
func TestCatalogDoesNotAdvertiseUnobservedLockdown(t *testing.T) {
	root := filepath.Join("..", "..")
	paths, err := filepath.Glob(filepath.Join(root, "vm", "profiles", "*.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	lockdownNamed := map[string]bool{}
	for _, path := range paths {
		p, err := LoadProfile(path)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(strings.ToLower(p.Version), "lockdown") {
			t.Errorf("%s: version %q advertises lockdown, which no executor path establishes; version is the distribution release (see docs/profile-claims.md)", p.ID, p.Version)
		}
		if strings.Contains(strings.ToLower(p.ID), "lockdown") {
			lockdownNamed[p.ID] = true
		}
	}
	for _, hm := range loadHandMaintainedMatrices(t, root) {
		for _, id := range requiredLockdownEntries(hm.m, lockdownNamed) {
			t.Errorf("%s: %s is required (explicitly or by omitting `required`), but kernel lockdown is not established in its guest; mark it required: false (see docs/profile-claims.md)", hm.file, id)
		}
	}
}

// The guard must read `required` the way the runner does: an entry that omits
// it is required.
func TestRequiredLockdownEntriesUsesRunnerDefault(t *testing.T) {
	named := map[string]bool{"x-lockdown": true}
	for name, body := range map[string]string{
		"omitted":  "name: t\nprofiles:\n  - id: x-lockdown\n",
		"explicit": "name: t\nprofiles:\n  - id: x-lockdown\n    required: true\n",
	} {
		m, err := matrix.LoadBytes([]byte(body))
		if err != nil {
			t.Fatal(err)
		}
		if got := requiredLockdownEntries(m, named); len(got) != 1 {
			t.Errorf("%s: want the lockdown entry reported as required, got %v", name, got)
		}
	}
	m, err := matrix.LoadBytes([]byte("name: t\nprofiles:\n  - id: x-lockdown\n    required: false\n"))
	if err != nil {
		t.Fatal(err)
	}
	if got := requiredLockdownEntries(m, named); len(got) != 0 {
		t.Errorf("required: false: want nothing reported, got %v", got)
	}
}

// zeroRequiredAllowed lists hand-maintained matrices that predate this check
// and have no required target. They are opt-in, operator-supplied-image
// evidence matrices; RunVerdict ignores optional targets, so a run of them
// reports COMPATIBLE whatever the artifact does. Do not add to this list:
// give a new matrix at least one required target instead.
var zeroRequiredAllowed = map[string]bool{
	"rhcos.yaml":       true,
	"rhcos-arm64.yaml": true,
}

// schema.RunVerdict only considers required targets, so a matrix with none
// returns COMPATIBLE (exit 0, "All required profiles passed") even when every
// target is INCOMPATIBLE. A shipped matrix must not be able to give that
// false green.
func TestHandMaintainedMatricesHaveARequiredTarget(t *testing.T) {
	for _, hm := range loadHandMaintainedMatrices(t, filepath.Join("..", "..")) {
		if requiredCount(hm.m) == 0 && !zeroRequiredAllowed[hm.file] {
			t.Errorf("%s has no required target: RunVerdict would report COMPATIBLE for an artifact that fails on every target; mark at least one observed-identity profile required", hm.file)
		}
	}
}
